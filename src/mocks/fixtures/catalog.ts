function buildEditions(seed: Seed): Edition[] {
  const [oneOfOne, tenth, fiftieth, open] = seed.stock
  const p = seed.price
  const mk = (id: string, label: string, price: string, available: number, total: number | null, maxPerOrder: number, unavailable = false): Edition => ({
    id,
    label,
    price: eth.normalize(price),
    available,
    total,
    maxPerOrder,
    status: unavailable ? 'unavailable' : available <= 0 ? 'sold_out' : 'available',
  })
  return [
    mk('1of1', '1/1', eth.of(p).times(2.4).toDecimalPlaces(2).toString(), oneOfOne, 1, 1, seed.oneOfOneUnavailable),
    mk('1of10', '1/10', eth.of(p).times(1.35).toDecimalPlaces(2).toString(), tenth, 10, Math.min(5, Math.max(tenth, 1))),
    mk('1of50', '1/50', p, fiftieth, 50, 10),
    mk('open', 'ABERTA', eth.of(p).times(0.6).toDecimalPlaces(2).toString(), open, null, 10),
  ]
}

const NOW = Date.UTC(2026, 9, 28, 12, 0, 0) // fixed "now" for deterministic listing dates

export function buildCatalog(): NftDetail[] {
  return seeds.map((s) => {
    const editions = buildEditions(s)
    const available = editions.filter((e) => e.status === 'available').reduce((acc, e) => acc + Math.min(e.available, 50), 0)
    const listedAt = new Date(NOW - s.daysAgo * 86_400_000).toISOString()
    return {
      id: s.id,
      tokenId: s.tokenId,
      name: s.name,
      collection: s.collection,
      category: s.category,
      network: s.network,
      image: imageUrl(s.image),
      imageAlt: IMAGE_ALT[s.image],
      price: eth.normalize(s.price),
      compareAtPrice: s.compareAtPrice ? eth.normalize(s.compareAtPrice) : null,
      badge: s.badge ?? null,
      trending: Boolean(s.trending),
      listedAt,
      available,
      version: 1,
      description: `Um colecionável digital finalizado à mão da coleção Kurio Editions, verificado na ${NETWORK_LABELS[s.network]}, com arte desbloqueável e acesso para colecionadores.`,
      about: `${s.name} é uma obra digital 1/50 finalizada à mão da coleção Kurio Editions. Cada atributo fica armazenado nos metadados do token e verificado na ${NETWORK_LABELS[s.network]}. A obra explora identidade, movimento e luz em um mundo digital sem fronteiras.\n\nA propriedade inclui a arte em alta resolução, lançamentos exclusivos para colecionadores e um registro permanente de procedência registrada na rede. ${s.creator} recebe 5% de direitos autorais nas vendas secundárias, apoiando novos trabalhos e lançamentos da comunidade.`,
      gallery: [imageUrl(s.image), imageUrl(s.image), imageUrl(s.image), imageUrl(s.image)],
      creator: s.creator,
      royaltyPercent: 5,
      contract: CONTRACTS[s.network],
      standard: s.network === 'solana' ? 'Metaplex' : 'ERC-721',
      attributes: s.attributes,
      rating: 4.8,
      reviewsCount: 19,
      editions,
      defaultEditionId: '1of50',
      priceUpdatedAt: listedAt,
    }
  })
}
